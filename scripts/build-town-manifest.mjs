#!/usr/bin/env node
/**
 * Building-kit manifest (P6).
 *
 * Scans public/town/*.glb and writes src/lib/townManifest.ts: one entry per
 * module with its kind and its size, read from the GLB's own bounding box, so
 * nobody has to maintain a size table by hand. It is also the spec validator:
 * it warns when a module breaks the rules in docs/ASSET_SPEC.md (origin not at
 * the footprint centre on the ground, size out of range, too many triangles).
 *
 *   file prefix   kind        meaning
 *   bld-*         frontage    walk-ups that line the streets
 *   tall-*        tall        skyline blocks
 *   back-*        backdrop    low buildings, seen in the distance
 *
 * With no files in public/town/ the manifest is empty and the town keeps using
 * the Kenney models, unchanged.
 *
 * Usage
 *   pnpm assets:town            regenerate the manifest
 *   pnpm assets:town --check    fail if the committed manifest is out of date (CI)
 *
 * Run it on the GLBs *before* `pnpm assets:optimize`: quantised (compressed)
 * positions no longer carry real-world min/max.
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const DIR = join(process.cwd(), 'public', 'town')
const OUT = join(process.cwd(), 'src', 'lib', 'townManifest.ts')
const CHECK = process.argv.includes('--check')

const KINDS = { bld: 'frontage', tall: 'tall', back: 'backdrop' }
// [minWidth, maxWidth, minHeight, maxHeight] in metres, from docs/ASSET_SPEC.md
const RANGE = {
  frontage: [3.5, 11, 5, 13],
  tall: [7, 11, 16, 32],
  backdrop: [7, 13, 6, 16],
}

const problems = []
const warnings = []

function readGlbJson(file) {
  const b = readFileSync(file)
  if (b.readUInt32LE(0) !== 0x46546c67) throw new Error('not a binary glTF (.glb)')
  return JSON.parse(b.subarray(20, 20 + b.readUInt32LE(12)).toString('utf8'))
}

function describe(file) {
  const name = file.replace(/\.glb$/, '')
  const prefix = name.split('-')[0]
  const kind = KINDS[prefix]
  if (!kind) {
    problems.push(`${file}: name must start with bld- (frontage), tall- or back-`)
    return null
  }
  const json = readGlbJson(join(DIR, file))
  const min = [Infinity, Infinity, Infinity]
  const max = [-Infinity, -Infinity, -Infinity]
  let tris = 0
  let meshes = 0
  for (const mesh of json.meshes ?? []) {
    for (const prim of mesh.primitives) {
      const a = json.accessors[prim.attributes.POSITION]
      if (!a.min || !a.max) {
        problems.push(`${file}: POSITION accessor has no min/max`)
        return null
      }
      if (a.componentType !== 5126) {
        problems.push(`${file}: positions are quantised. Run this script before assets:optimize, or export without quantisation`)
        return null
      }
      for (let i = 0; i < 3; i++) {
        min[i] = Math.min(min[i], a.min[i])
        max[i] = Math.max(max[i], a.max[i])
      }
      tris += prim.indices != null ? json.accessors[prim.indices].count / 3 : a.count / 3
    }
    meshes++
  }
  if (meshes === 0) {
    problems.push(`${file}: contains no meshes`)
    return null
  }
  // Node transforms are not applied here (the size would be wrong): reject them.
  for (const n of json.nodes ?? []) {
    if (n.mesh == null) continue
    const s = n.scale ?? [1, 1, 1]
    const r = n.rotation ?? [0, 0, 0, 1]
    const t = n.translation ?? [0, 0, 0]
    const identity = s.every((v) => Math.abs(v - 1) < 1e-4) && r.slice(0, 3).every((v) => Math.abs(v) < 1e-4) && t.every((v) => Math.abs(v) < 1e-4)
    if (!identity) warnings.push(`${file}: a mesh node has a transform. Apply transforms before export, or the size below is wrong`)
  }
  const size = max.map((v, i) => +(v - min[i]).toFixed(3))
  const cx = (min[0] + max[0]) / 2
  const cz = (min[2] + max[2]) / 2
  if (Math.abs(min[1]) > 0.05) warnings.push(`${file}: bottom is at y=${min[1].toFixed(2)}; the origin must be on the ground (y=0)`)
  if (Math.abs(cx) > 0.25 || Math.abs(cz) > 0.25) warnings.push(`${file}: footprint centre is at (${cx.toFixed(2)}, ${cz.toFixed(2)}); the origin must be the footprint centre`)
  const [w0, w1, h0, h1] = RANGE[kind]
  if (size[0] < w0 || size[0] > w1) warnings.push(`${file}: width ${size[0]}m is outside ${w0}-${w1}m for a ${kind} module`)
  if (size[1] < h0 || size[1] > h1) warnings.push(`${file}: height ${size[1]}m is outside ${h0}-${h1}m for a ${kind} module`)
  if (tris > 3000) warnings.push(`${file}: ${Math.round(tris)} triangles; the spec asks for 400-1500`)
  if (meshes > 1) warnings.push(`${file}: ${meshes} meshes; only the FIRST is used, merge them into one`)
  return { file: `town/${file}`, kind, size }
}

const files = existsSync(DIR) ? readdirSync(DIR).filter((f) => f.endsWith('.glb')).sort() : []
const models = files.map(describe).filter(Boolean)

const body = `// GENERATED by scripts/build-town-manifest.mjs. Do not edit; run \`pnpm assets:town\`.
// Sizes are read from each GLB in public/town/. Empty means "use the Kenney models".

export type TownKind = 'frontage' | 'tall' | 'backdrop'

export interface TownModel {
  /** path under public/, e.g. town/bld-3-6m-a.glb */
  file: string
  kind: TownKind
  /** width (x), height (y), depth (z) in metres */
  size: [number, number, number]
}

export const TOWN_MODELS: TownModel[] = ${JSON.stringify(models, null, 2)}
`

for (const w of warnings) console.warn('warning:', w)
for (const p of problems) console.error('error:  ', p)
if (problems.length) process.exit(1)

if (CHECK) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : ''
  if (current !== body) {
    console.error('src/lib/townManifest.ts is out of date. Run `pnpm assets:town` and commit it.')
    process.exit(1)
  }
  console.log(`town manifest up to date (${models.length} module${models.length === 1 ? '' : 's'})`)
} else {
  writeFileSync(OUT, body)
  const byKind = models.reduce((m, x) => ({ ...m, [x.kind]: (m[x.kind] ?? 0) + 1 }), {})
  console.log(`wrote ${OUT.replace(process.cwd() + '\\', '').replace(process.cwd() + '/', '')}: ${models.length} module(s) ${JSON.stringify(byKind)}${warnings.length ? `, ${warnings.length} warning(s)` : ''}`)
}
